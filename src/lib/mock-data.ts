export const generateLogEntries = (count: number, source: string): LogEntry[] => {
  const levels: LogEntry['level'][] = ['info', 'info', 'info', 'warn', 'debug']
  const messages = [
    'Request processed successfully',
    'Cache miss - fetching from database',
    'Rate limit: 450/500 requests used',
    'Connection pool at 80% capacity',
    'Scheduled task completed in 234ms',
    'Outgoing webhook delivered',
    'JWT token refreshed for user',
    'Database query took 89ms',
  ]
  return Array.from({ length: count }, (_, i) => ({
    id: `log_${i}`,
    timestamp: new Date(Date.now() - (count - i) * 30000).toISOString(),
    level: levels[Math.floor(Math.random() * levels.length)],
    message: messages[Math.floor(Math.random() * messages.length)],
    source,
  }))
}
